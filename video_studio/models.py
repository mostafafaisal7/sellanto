class VideoTemplate(models.Model):
    """
    Reusable video templates for common use cases
    """
    name = models.CharField(max_length=200)
    description = models.TextField()

    CATEGORY_CHOICES = [
        ('product_launch', 'Product Launch'),
        ('social_ad', 'Social Media Ad'),
        ('unboxing', 'Unboxing Experience'),
        ('showcase', 'Product Showcase'),
        ('lifestyle', 'Lifestyle Video'),
        ('testimonial', 'Testimonial'),
        ('tutorial', 'Tutorial/How-To'),
        ('comparison', 'Product Comparison'),
    ]
    category = models.CharField(max_length=50, choices=CATEGORY_CHOICES)

    # Template configuration
    clips_config = models.JSONField(default=list, help_text="List of clip configurations")
    """
    Example clips_config:
    [
        {
            'type': 'hero_reveal',
            'duration': 8,
            'prompt': 'Dramatic product reveal with dynamic lighting',
            'camera_movement': 'dolly_in',
            'lighting': 'dramatic'
        },
        {
            'type': '360_rotation',
            'duration': 8,
            'prompt': 'Smooth 360° orbit around product',
            'camera_movement': 'orbit',
            'lighting': 'studio'
        }
    ]
    """

    transition_type = models.CharField(max_length=20, default='crossfade')
    recommended_duration = models.IntegerField(help_text="Total recommended duration in seconds")
    aspect_ratio = models.CharField(max_length=10, default='16:9')

    # Availability
    is_global = models.BooleanField(default=False, help_text="Available to all users")
    is_active = models.BooleanField(default=True)
    created_by = models.ForeignKey(User, on_delete=models.CASCADE, null=True, blank=True)

    # Preview
    preview_video = models.FileField(upload_to=template_video_path, blank=True, null=True)
    preview_thumbnail = models.ImageField(upload_to=template_video_path, blank=True, null=True)

    # Usage stats
    times_used = models.IntegerField(default=0)
    avg_rating = models.FloatField(default=0)

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'video_studio_templates'
        ordering = ['-times_used', 'name']
        verbose_name = 'Video Template'
        verbose_name_plural = 'Video Templates'

    def __str__(self):
        return f"{self.name} ({self.category})"

    def increment_usage(self):
        """Increment usage counter"""
        self.times_used += 1
        self.save(update_fields=['times_used'])

    def update_rating(self, new_rating):
        """Update average rating with new rating"""
        if self.avg_rating == 0:
            self.avg_rating = new_rating
        else:
            # Simple moving average
            self.avg_rating = (self.avg_rating * 0.9) + (new_rating * 0.1)
        self.save(update_fields=['avg_rating'])


class ABTestVariant(models.Model):
    """
    A/B testing variants for video optimization
    """
    project = models.ForeignKey(VideoProject, on_delete=models.CASCADE, related_name='ab_variants')
    clip = models.ForeignKey(VideoClip, on_delete=models.CASCADE, related_name='variants')

    variant_name = models.CharField(max_length=100, help_text="Variant A, B, C, etc.")
    variant_config = models.JSONField(default=dict, help_text="Variant-specific settings")

    # Performance metrics
    views = models.IntegerField(default=0)
    clicks = models.IntegerField(default=0)
    engagement_rate = models.FloatField(default=0)
    conversion_rate = models.FloatField(default=0)
    watch_time_avg = models.FloatField(default=0, help_text="Average watch time in seconds")

    # Results
    is_winner = models.BooleanField(default=False)
    confidence_score = models.FloatField(default=0, help_text="Statistical confidence 0-1")

    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = 'video_studio_ab_variants'
        ordering = ['-engagement_rate']
        verbose_name = 'A/B Test Variant'
        verbose_name_plural = 'A/B Test Variants'

    def __str__(self):
        return f"{self.variant_name} - {self.project.name}"

    def calculate_score(self):
        """Calculate composite performance score"""
        return (
            (self.engagement_rate * 0.3) +
            (self.conversion_rate * 0.4) +
            (min(self.watch_time_avg / 8.0, 1.0) * 0.3)  # Normalize to 8s
        )
